// The update signing key. The private key lives only in the login keychain; the public key is
// written to Sources/UpdateKey.swift and built into the app, which installs only signed updates.
//   swift scripts/update-key.swift generate     create the key once (make update-key)
//   swift scripts/update-key.swift sign FILE    print the signature of FILE (used by package.sh)
import CryptoKit
import Foundation
import Security

let service = "io.github.sayre4ux.typethru.update-signing"
let account = "ed25519"
let keyFile = "Sources/UpdateKey.swift"

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data((message + "\n").utf8))
    exit(1)
}

func storedKey() -> Curve25519.Signing.PrivateKey? {
    let query: [String: Any] = [kSecClass as String: kSecClassGenericPassword, kSecAttrService as String: service,
                                kSecAttrAccount as String: account, kSecReturnData as String: true]
    var item: CFTypeRef?
    guard SecItemCopyMatching(query as CFDictionary, &item) == errSecSuccess, let data = item as? Data else { return nil }
    return try? Curve25519.Signing.PrivateKey(rawRepresentation: data)
}

/// The public key built into the app, read back from Sources/UpdateKey.swift.
func builtInKey() -> String? {
    guard let source = try? String(contentsOfFile: keyFile, encoding: .utf8),
          let start = source.range(of: "base64Encoded: \"")?.upperBound,
          let end = source[start...].firstIndex(of: "\"") else { return nil }
    return String(source[start..<end])
}

let arguments = CommandLine.arguments.dropFirst()
switch (arguments.first, arguments.count) {
case ("generate", 1):
    if storedKey() != nil { fail("An update signing key already exists in your login keychain. Keep using it.") }
    let key = Curve25519.Signing.PrivateKey()
    let item: [String: Any] = [kSecClass as String: kSecClassGenericPassword, kSecAttrService as String: service,
                               kSecAttrAccount as String: account, kSecAttrLabel as String: "TypeThru update signing key",
                               kSecValueData as String: key.rawRepresentation]
    let status = SecItemAdd(item as CFDictionary, nil)
    guard status == errSecSuccess else { fail("Could not save the key in the keychain (error \(status)).") }
    let source = """
    import Foundation

    // Generated by make update-key. The app installs only updates signed with the matching private
    // key, which is kept in the release signer's keychain.
    enum UpdateKey {
        static let publicKey = Data(base64Encoded: "\(key.publicKey.rawRepresentation.base64EncodedString())")! // gitleaks:allow (public key)
    }

    """
    try! source.write(toFile: keyFile, atomically: true, encoding: .utf8)
    print("Saved the private key in your login keychain as \"TypeThru update signing key\" and wrote \(keyFile).")
    print("Back it up (for example in a password manager): without it, users must reinstall from the disk image.")
case ("sign", 2):
    guard let key = storedKey() else { fail("No update signing key in your login keychain. Run: make update-key") }
    guard builtInKey() == key.publicKey.rawRepresentation.base64EncodedString() else {
        fail("The keychain key does not match \(keyFile), so the app would refuse this update.")
    }
    guard let data = FileManager.default.contents(atPath: arguments.last!) else { fail("Cannot read \(arguments.last!).") }
    print(try! key.signature(for: data).base64EncodedString())
default:
    fail("Usage: swift scripts/update-key.swift generate | sign FILE")
}
